const assert = require('assert');
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const repo = '/home/ubuntu/novasocial';
const html = fs.readFileSync(path.join(repo, 'index.html'), 'utf8');
const decoder = fs.readFileSync(path.join(repo, 'src', 'features', 'url-base64-to-uint8-array.js'), 'utf8');
const contract = fs.readFileSync(path.join(repo, 'docs', 'push-vapid-403-diagnosis-contract.md'), 'utf8');
const logPath = '/home/ubuntu/upload/pasted_content.txt';
const userLog = fs.readFileSync(logPath, 'utf8');
const keyMatch = html.match(/const VAPID_PUBLIC_KEY = '([^']+)'/);
assert(keyMatch, 'Branch2 VAPID public key must be present');
const key = keyMatch[1];
const raw = Buffer.from(key.replace(/-/g, '+').replace(/_/g, '/') + '='.repeat((4 - key.length % 4) % 4), 'base64');
const p = BigInt('0xffffffff00000001000000000000000000000000ffffffffffffffffffffffff');
const a = p - 3n;
const b = BigInt('0x5ac635d8aa3a93e7b3ebbd55769886bc651d06b0cc53b0f63bce3c3e27d2604b');
const x = raw.length === 65 ? BigInt('0x' + raw.subarray(1, 33).toString('hex')) : 0n;
const y = raw.length === 65 ? BigInt('0x' + raw.subarray(33, 65).toString('hex')) : 0n;
const curveValid = raw.length === 65 && raw[0] === 0x04 && x < p && y < p && ((y * y - (x * x * x + a * x + b)) % p === 0n);
const logHas403 = /statusCode=403/.test(userLog);
const logHasCurveError = /VAPID public key must be on the P-256 curve/.test(userLog);
const logHasZeroOfSeven = /FINAL sent=0\/7/.test(userLog);
const logHasSevenSubscriptions = /subscriptions found=7/.test(userLog);
assert.strictEqual(key.length, 87, 'Branch2 public key length must match the attached Edge Function log');
assert.strictEqual(raw.length, 65, 'Branch2 public key must decode to the expected uncompressed point length');
assert.strictEqual(raw[0], 0x04, 'Branch2 public key must use the uncompressed-point prefix');
assert.strictEqual(curveValid, false, 'diagnosis fixture must reproduce the invalid P-256 point');
assert(decoder.includes("window.atob(base64)"), 'decoder must use Base64URL decoding');
assert(decoder.includes('new Uint8Array(rawData.length)'), 'decoder must copy decoded bytes');
assert(!decoder.includes('fetch('), 'decoder must not perform network calls');
assert(!decoder.includes('db.'), 'decoder must not perform database operations');
assert(logHas403 && logHasCurveError && logHasZeroOfSeven && logHasSevenSubscriptions, 'attached evidence must contain the repeated 403/curve/0-of-7 pattern');
assert(contract.includes('CONFIGURATION_BLOCKED'), 'diagnosis contract must preserve the configuration-blocked decision');
assert(contract.includes('private key'), 'diagnosis contract must preserve private-key handling guidance');

console.log('PUSH_VAPID_403_DIAGNOSIS_HARNESS=PASS');
